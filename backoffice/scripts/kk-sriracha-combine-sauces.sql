-- Соус шрирача 50₽ + комбинирование доп. соусов (Kebab King)
-- 1) Цена «Соус острый ШриРача» = 50
-- 2) Группа «Соусы дополнительно» — без лимита max_select (можно несколько)
-- 3) Переносим шрирачу в основную группу «Соусы» как платный доп (удобнее комбинировать
--    с кетчупом/горчицей и т.д. в одном списке), либо оставляем в дополнительно —
--    оставляем в «Соусы дополнительно», но снимаем лимит.

BEGIN;

UPDATE modifiers
SET price = 50
WHERE id = 122 AND name ILIKE '%ШриРача%';

UPDATE modifier_groups
SET max_select = NULL
WHERE id = 7 AND name = 'Соусы дополнительно';

-- На всякий случай основная группа «Соусы» тоже без лимита
UPDATE modifier_groups
SET max_select = NULL
WHERE id = 5 AND name = 'Соусы';

COMMIT;
